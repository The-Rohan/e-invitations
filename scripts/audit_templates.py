"""Build a versioned text/section inventory from the original ten HTML templates."""
from html.parser import HTMLParser
from pathlib import Path
import json,re,html,hashlib
class Inventory(HTMLParser):
 def __init__(self,source):
  super().__init__(convert_charrefs=False);self.source=source;self.offsets=[0];self.stack=[];self.sections=[];self.fields=[]
  for m in re.finditer('\n',source):self.offsets.append(m.end())
 def position_index(self):l,c=self.getpos();return self.offsets[l-1]+c
 def handle_starttag(self,tag,attrs):
  a=dict(attrs);pos=self.position_index();node={'tag':tag,'start':pos,'inner':pos+len(self.get_starttag_text()),'attrs':a}
  if tag=='section':
   node['section']=len(self.sections);self.sections.append({'key':'section-'+str(node['section']),'id':a.get('id',''),'className':a.get('class',''),'start':pos})
  node['parentSection']=next((n['section'] for n in reversed(self.stack) if 'section'in n),None)
  if tag=='section':node['parentSection']=node['section']
  if 'data-ur'in a:
   node['copy']=len(self.fields);self.fields.append({'key':'copy-'+str(node['copy']),'tag':tag,'className':a.get('class',''),'elementId':a.get('id',''),'section':node['parentSection'],'ur':plain(a['data-ur'])})
  if tag not in ['br','img','input','source','meta','link','hr','i-not-void','wbr','area','base','embed']:self.stack.append(node)
 def handle_endtag(self,tag):
  idx=next((i for i in range(len(self.stack)-1,-1,-1) if self.stack[i]['tag']==tag),None)
  if idx is None:return
  for node in self.stack[idx:]:
   if 'copy'in node:
    f=self.fields[node['copy']];f['en']=plain(node['attrs'].get('data-en',self.source[node['inner']:self.position_index()]))
   if 'section'in node:
    sec=self.sections[node['section']];body=self.source[node['start']:self.position_index()];sec['kind']=kind(body,sec['id']);sec['title']=sec['kind'].replace('_',' ').title()
  self.stack=self.stack[:idx]
def plain(s):return html.unescape(re.sub('<[^>]*>','\n',s)).strip()
def kind(body,id):
 if id in ['entrance','hero','invitation','reveal','events','dress','stay','travel','rsvp','foot']:return id
 for token,k in [('stzHost','event_details'),('discs','reveal'),('seals','reveal'),('fams','invitation'),('venueName','venue'),('evGrid','events'),('tlList','schedule'),('tlFrame','schedule'),('dressRules','dress'),('clAttire','dress'),('infoCards','travel_stay'),('hotelArt','stay'),('clTravel','travel'),('rsvpForm','rsvp'),('cdRow','countdown')]:
  if token in body:return k
 return id or 'content'
out={}
for p in sorted(Path('public/collection').glob('card-*.html')):
 source=p.read_text();i=Inventory(source);i.feed(source)
 for f in i.fields:
  f['group']=i.sections[f['section']]['kind'] if f['section'] is not None else 'controls'
  en=f.get('en','');f['managed']=bool(re.search(r'Bilal|Mahrukh|Abbasi|Kiyani|2027|Banjosa|Rawalakot|Three celebrations|three days|three evenings',en,re.I)) or f['className'] in ['venueName','venueWhere','venueAddr','heroDate','heroWhen','heroPlace','heroWhere','footWhen','fd','tm','pn','tlEnd','keyHint'] or f['group'] in ['rsvp']
  f['label']=(en.replace('\n',' ')[:70] or f['className'] or f['key'])
 for sec in i.sections:sec.pop('start',None)
 out[p.stem[5:]]={'sourceHash':hashlib.sha256(source.encode()).hexdigest(),'sections':i.sections,'fields':i.fields}
Path('lib/template-manifest.json').write_text(json.dumps(out,ensure_ascii=False,indent=2)+'\n')
Path('TEMPLATE_AUDIT.md').write_text('# Original template inventory\n\nGenerated by `python scripts/audit_templates.py`. Source hashes make changes to the original templates detectable. English/Urdu copy is inventoried individually; identity, event data and dates are managed by structured fields.\n\n| Design | Sections | Localized text nodes | Sections offered |\n|---|---:|---:|---|\n'+''.join(f"| {k} | {len(v['sections'])} | {len(v['fields'])} | {', '.join(dict.fromkeys(s['kind'] for s in v['sections']))} |\n" for k,v in out.items()))
print([(k,len(v['fields'])) for k,v in out.items()])
